import { launch, sleep, shot, tap, toScene, st } from './drive.mjs';
const { b, p, errors } = await launch();
await tap(p, 'Enter', 100); await sleep(200);
await toScene(p, 'gym', 'sanmik');
await sleep(1600);
await p.keyboard.down('ArrowUp'); await sleep(400);
const up = await p.evaluate(() => { const g = window.__SANMIK.gameplay; return { aim: g.player.aim.name, shots: g.combat.live().map(x => Math.round(x.body.velocity.y)) }; });
await p.keyboard.up('ArrowUp');
await shot(p, 'keys_up');
await p.keyboard.down('ArrowRight'); await sleep(300);
const fwd = await p.evaluate(() => window.__SANMIK.gameplay.combat.live().filter(x => x.team === 'player').length);
await p.keyboard.up('ArrowRight');
await tap(p, 'ArrowLeft', 80); await sleep(30);
const melee = await p.evaluate(() => window.__SANMIK.gameplay.combat.swings.length);
await p.evaluate(() => window.__SANMIK.cheat.meter()); await tap(p, 'ArrowDown', 80); await sleep(200);
const sp = await p.evaluate(() => window.__SANMIK.gameplay.player.specialActive);
await tap(p, 'w', 80); await sleep(100);
console.log(JSON.stringify({ up, fwd, melee, special: sp, jumps: (await st(p)).jumps }));
await sleep(800); await shot(p, 'keys_hint');
console.log('errors', errors.filter(e => !e.includes('GL Driver')));
await b.close();
